// Writes .env.local pointing the app at the local Supabase stack (`npm run db:start` first).
// Only the URL and the publishable key are written: both are safe for the browser.
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";

const target = ".env.local";
if (existsSync(target) && !process.argv.includes("--force")) {
  console.error(`${target} already exists. Re-run with --force to overwrite it.`);
  process.exit(1);
}

let status;
try {
  const output = execFileSync("npx", ["supabase", "status", "-o", "json"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  });
  status = JSON.parse(output.slice(output.indexOf("{")));
} catch {
  console.error("Local Supabase is not running. Start it with `npm run db:start`.");
  process.exit(1);
}

writeFileSync(
  target,
  [
    "# Generated by scripts/write-local-env.mjs for the local Supabase stack.",
    "NEXT_PUBLIC_APP_URL=http://localhost:3000",
    `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}`,
    "",
  ].join("\n"),
);
console.log(`Wrote ${target} for ${status.API_URL}`);
